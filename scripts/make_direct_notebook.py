#!/usr/bin/env python
"""Build notebooks/direct_vllm.ipynb: the direct-deployment (vLLM, no AirLLM) matrix for a
rented big GPU (Lightning AI Studio, or any Jupyter with a CUDA GPU and Internet).

The repo is private, so the notebook embeds the bench modules with %%writefile cells. Upload it
to the Studio, select an A100 / H100 machine and run all cells. The host tag is derived from
the GPU name (lightning-h100, lightning-a100, ...), and the last cell prints every result JSON.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["measure.py", "model_list.py", "run_direct.py", "run_direct_matrix.py"]
ap = argparse.ArgumentParser()
ap.add_argument("--out", default="notebooks/direct_vllm.ipynb")
ap.add_argument("--vllm", default="0.34.0")
ap.add_argument("--platform", default="lightning", help="host tag prefix")
ap.add_argument("--budget-min", type=float, default=40, help="start no new model after this many minutes")
ap.add_argument("--models", default="all")
ARGS = ap.parse_args()


def code(src):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": src.splitlines(keepends=True)}


def md(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


cells = [
    md("# Direct deployment with vLLM (no AirLLM)\n\n"
       "Gemma 4 (E2B-qat, E4B, 12B, 26B-A4B) and Qwen 3.5-9B / 3.6-27B / 3.8-27B on one big GPU. "
       "bf16 when the checkpoint fits in 75 % of VRAM, else vLLM fp8. "
       "Generated by `scripts/make_direct_notebook.py` in the airllm-benchmarks repo."),
    code("!nvidia-smi\n!df -h / /tmp /teamspace/studios/this_studio 2>/dev/null\n!free -g\n!nproc"),
    code("%%capture pip_log\n"
         f"!pip install -q 'vllm=={ARGS.vllm}' nvidia-ml-py psutil 'huggingface_hub[hf_xet]'"),
    code("import torch, transformers, vllm\n"
         "print('torch', torch.__version__, 'cuda', torch.version.cuda, torch.cuda.get_device_name(0))\n"
         "print('transformers', transformers.__version__, 'vllm', vllm.__version__)"),
    code("import os\nos.makedirs('airllm-benchmarks/bench', exist_ok=True)"),
]
for name in FILES:
    cells.append(code(f"%%writefile airllm-benchmarks/bench/{name}\n{(ROOT / 'bench' / name).read_text()}"))

cells += [
    code("import os, re, shutil, torch\n"
         "%cd airllm-benchmarks\n"
         "gpu = torch.cuda.get_device_name(0)\n"
         "m = re.search(r'(H200|H100|A100|L40S|L4|A10G|T4|B200|RTX PRO 6000)', gpu, re.I)\n"
         f"TAG = '{ARGS.platform}-' + (m.group(1).lower().replace(' ', '') if m else 'gpu')\n"
         "cands = [c for c in ['/tmp', '/cache', '/root', os.path.expanduser('~')] if os.path.isdir(c)]\n"
         "for c in cands: print(c, round(shutil.disk_usage(c).free / 1e9), 'GB free')\n"
         "SCRATCH = max(cands, key=lambda c: shutil.disk_usage(c).free)\n"
         "os.environ['HF_HOME'] = f'{SCRATCH}/hf'\n"
         "os.environ['BENCH_HOST_TAG'] = TAG\n"
         "print('GPU', gpu, '-> tag', TAG, '| HF_HOME', os.environ['HF_HOME'])"),
    code(f"!python bench/run_direct_matrix.py --models {ARGS.models} --out-dir results/{{TAG}} --cleanup "
         f"--budget-min {ARGS.budget_min:g}"),
    code("import json, glob\n"
         "for f in sorted(glob.glob(f'results/{TAG}/*.json')):\n"
         "    r = json.load(open(f)); s = r['runs'].get('single', {}); b = r['runs'].get('batch', {})\n"
         "    print(f\"{r['model']:30s} {r['engine']}-{r['weights']:5s} {r['status']:5s} load {r['phases'].get('load_s')}s \"\n"
         "          f\"ttft {s.get('ttft_s')}s decode {s.get('decode_tok_per_s')} tok/s batch {b.get('output_tok_per_s')} tok/s \"\n"
         "          f\"| {r.get('error', '')[:150]}\")"),
    code("import json, glob\n"
         "for f in sorted(glob.glob(f'results/{TAG}/*.json')):\n"
         "    r = json.load(open(f)); r.pop('engine_log_tail', None)\n"
         "    print('@@@RESULT', f.split('/')[-1]); print(json.dumps(r)); print('@@@END')"),
]

nb = {"cells": cells,
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                   "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 5}
out = ROOT / ARGS.out
out.parent.mkdir(exist_ok=True)
out.write_text(json.dumps(nb, indent=1))
print(f"wrote {out} ({out.stat().st_size / 1e3:.0f} kB, {len(cells)} cells)")
